export const STR = { en, fr };
export type StrKey = keyof typeof en;

export function tr(lang: Lang, key: StrKey, vars?: Record<string, string | number>) {
  let s: string = STR[lang][key] ?? STR.en[key];
  if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, String(vars[k]));
  return s;
}

